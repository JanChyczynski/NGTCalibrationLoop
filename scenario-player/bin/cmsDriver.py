#!/usr/bin/env python3
"""
(FAKE) stand-in for CMSSW's `cmsDriver.py`.

The real tool builds a full cmsRun python config from a step recipe. This fake
doesn't do any physics -- it just figures out, from the same command-line flags
the calibration loop passes, what output file(s) a real run would eventually
produce, and writes that into the generated python config as a marker comment
that scenario-player/bin/cmsRun reads back later:

- `--fileout file:X`            -> output is X verbatim (Step 2's express jobs)
- `-s ...ALCAHARVEST:...`       -> output is promptCalibConditions.db (Step 4;
                                    this is CMSSW's own fixed harvesting output
                                    name, which is why NGTLoopStep4.py's generated
                                    script explicitly checks for that filename)
- `-s ...ALCA:<Producer>...`    -> output is <Producer>.root (Step 3; CMSSW's
                                    convention for naming ALCARECO output after
                                    the ALCA producer module)

All three of NGTLoopStep{2,3,4}.py's actual cmsDriver.py invocations were read
directly from those scripts to derive this -- see their PrepareExpressJobs /
PrepareAlCaPromptJobs / PrepareHarvestingJobs.

The generated config also records the job's *inputs* as a `# FAKE_INPUTS=...`
marker, which scenario-player/bin/cmsRun reads back to work out which
calibration/run/lumisections an output covers (see
scenario-player/bin/_fakeprov.py). All three steps pass them as one
comma-joined --filein list, each entry prefixed `file:` (step3/step4) or
`root://eoscms.cern.ch/` (step2's raw EOS reads) -- both stripped here so the
marker holds plain paths.
"""
import re
import sys

FILEIN_PREFIXES = ("root://eoscms.cern.ch/", "file:")


def _strip_filein_prefix(path):
    for prefix in FILEIN_PREFIXES:
        if path.startswith(prefix):
            return path[len(prefix):]
    return path


def determine_outputs(argv):
    python_filename = None
    fileout = None
    step_string = None

    i = 0
    while i < len(argv):
        if argv[i] == "--python_filename" and i + 1 < len(argv):
            python_filename = argv[i + 1]
        elif argv[i] == "--fileout" and i + 1 < len(argv):
            fileout = argv[i + 1]
        elif argv[i] == "-s" and i + 1 < len(argv):
            step_string = argv[i + 1]
        i += 1

    if fileout and fileout.startswith("file:"):
        outputs = [fileout[len("file:"):]]
    elif step_string and "ALCAHARVEST:" in step_string:
        outputs = ["promptCalibConditions.db"]
    elif step_string:
        match = re.search(r"ALCA:(\w+)", step_string)
        outputs = [f"{match.group(1)}.root"] if match else []
    else:
        outputs = []

    return python_filename, outputs


def determine_inputs(argv):
    """The job's input files, from the one comma-joined --filein list all three
    steps build, with the `file:`/`root://` prefixes stripped."""
    for i, arg in enumerate(argv):
        if arg == "--filein" and i + 1 < len(argv):
            return [_strip_filein_prefix(p) for p in argv[i + 1].split(",") if p]
    return []


def main():
    argv = sys.argv[1:]
    python_filename, outputs = determine_outputs(argv)
    inputs = determine_inputs(argv)

    if not python_filename:
        print("(FAKE) cmsDriver.py: no --python_filename given, nothing to write", file=sys.stderr)
        sys.exit(1)

    with open(python_filename, "w", encoding="utf-8") as f:
        f.write("# (FAKE) generated by scenario-player/bin/cmsDriver.py -- not a real CMSSW config\n")
        f.write(f"# FAKE_OUTPUTS={','.join(outputs)}\n")
        f.write(f"# FAKE_INPUTS={','.join(inputs)}\n")

    print(f"(FAKE) cmsDriver.py: wrote {python_filename}, expected outputs={outputs}, {len(inputs)} input(s)")


if __name__ == "__main__":
    main()
